/**
 * Generate Tech Icons Data
 * Extracts SVG data from tech-stack-icons package at build time
 * Generates a TS module with light/dark variants for needed icons
 * Falls back to simple-icons for icons not in tech-stack-icons
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = join(__dirname, '..');
const OUTPUT_DIR = join(PROJECT_ROOT, 'src', 'data');

// Icons we need mapped to their tech-stack-icons name
const TECH_STACK_MAP = {
  'Astro': 'astro',
  'TypeScript': 'typescript',
  'React': null, // Use simple-icons for standard React atom icon
  'Vue': 'vuejs',
  'Node.js': 'nodejs',
  'Python': 'python',
  'Next.js': 'nextjs',
  'Go': 'go',
  'SQLite': 'sqlite',
  'Bootstrap': null, // Use simple-icons for standard purple Bootstrap icon
  'PostgreSQL': 'postgresql',
  'Drizzle': 'drizzle',
  'Git': 'git',
  'Stripe': 'stripe',
  'Tailwind CSS': 'tailwindcss',
  'GSAP': 'gsap',
  'Alpine.js': 'alpinejs',
  'Vite': 'vitejs',
  'HTML5': 'html5',
  'React Query': 'reactquery',
  'Playwright': 'playwright',
  'Framer Motion': 'framer',
  'Google Gemini': 'gemini',
  'CSS': 'css3', // Use css3 for proper blue CSS3 shield icon
  'TensorFlow': 'tensorflow',
  'JavaScript': null,
  'Gin': null,
  'HTMX': null,
  'Axios': null,
  'LaTeX': null,
  'Anime.js': null,
  'JSON Web Tokens': null,
};

// These icons fall back to simple-icons
const FALLBACK_TECHS = new Set([
  'JavaScript', 'Gin', 'HTMX', 'Axios', 'LaTeX', 'Anime.js', 'JSON Web Tokens',
  'React', 'Bootstrap',
]);

function extractIconData(packagePath) {
  if (!existsSync(packagePath)) {
    console.error(`❌ tech-stack-icons not found at: ${packagePath}`);
    console.error('   Run: npm install tech-stack-icons@latest');
    process.exit(1);
  }

  const content = readFileSync(packagePath, 'utf-8');
  const dataStart = content.indexOf('var f={');
  if (dataStart < 0) {
    console.error('❌ Could not find icon data in tech-stack-icons');
    process.exit(1);
  }
  const data = content.substring(dataStart + 6);

  const result = {};
  let found = 0;
  let missing = [];

  for (const [displayName, pkgName] of Object.entries(TECH_STACK_MAP)) {
    if (!pkgName) {
      missing.push(displayName);
      continue;
    }

    const pat = pkgName + ':{svg:{';
    // Use comma/brace prefix to avoid substring collisions (e.g. "go" matching inside "django")
    let start = data.indexOf(',' + pat);
    if (start < 0) {
      start = data.indexOf('{' + pat); // first entry in the object
    }
    if (start >= 0) start += 1; // skip delimiter
    if (start < 0) {
      missing.push(displayName);
      continue;
    }

    // Extract light SVG
    const lightStart = data.indexOf("'<svg", start);
    if (lightStart < 0) continue;
    const lightEnd = data.indexOf("'", lightStart + 1);
    if (lightEnd < 0) continue;
    let lightSvg = data.substring(lightStart + 1, lightEnd);

    // Extract dark SVG
    const darkStart = data.indexOf("'<svg", lightEnd);
    if (darkStart < 0) {
      // Some icons only have one variant
      result[displayName] = { svg: lightSvg };
      found++;
      continue;
    }
    const darkEnd = data.indexOf("'", darkStart + 1);
    if (darkEnd < 0) continue;
    let darkSvg = data.substring(darkStart + 1, darkEnd);

    result[displayName] = { light: lightSvg, dark: darkSvg };
    found++;
  }

  console.log(`✅ Extracted ${found} icons from tech-stack-icons`);
  if (missing.length > 0) {
    console.log(`⚠️  ${missing.length} icons will use simple-icons fallback: ${missing.join(', ')}`);
  }
  return result;
}

function generateTSModule(iconData) {
  let lines = [];

  lines.push('// Auto-generated by scripts/generate-tech-icons.mjs');
  lines.push('// Do not edit directly. Run: node scripts/generate-tech-icons.mjs');
  lines.push('');
  lines.push('export type IconVariant = "light" | "dark";');
  lines.push('');
  lines.push('export interface TechIconData {');
  lines.push('  light?: string;');
  lines.push('  dark?: string;');
  lines.push('  svg?: string; // single variant fallback');
  lines.push('}');
  lines.push('');

  const iconMap = {};
  for (const [name, data] of Object.entries(iconData)) {
    const key = name.replace(/[^a-zA-Z0-9]/g, '_');
    iconMap[name] = key;
    lines.push(`const _${key}: TechIconData = ${JSON.stringify(data)};`);
    lines.push('');
  }

  lines.push('const iconRegistry: Record<string, TechIconData> = {');
  const entries = Object.entries(iconMap);
  for (let i = 0; i < entries.length; i++) {
    const [name, key] = entries[i];
    const comma = i < entries.length - 1 ? ',' : '';
    lines.push(`  "${name}": _${key}${comma}`);
  }
  lines.push('};');
  lines.push('');

  lines.push('export function getTechIcon(name: string): TechIconData | null {');
  lines.push('  return iconRegistry[name] || null;');
  lines.push('}');
  lines.push('');

  // Fallback techs (simple-icons)
  lines.push('// These icons use simple-icons as fallback');
  lines.push('export const FALLBACK_TECHS: string[] = [');
  const fallbackArr = Array.from(FALLBACK_TECHS).sort();
  for (let i = 0; i < fallbackArr.length; i++) {
    const comma = i < fallbackArr.length - 1 ? ',' : '';
    lines.push(`  "${fallbackArr[i]}"${comma}`);
  }
  lines.push('];');
  lines.push('');

  return lines.join('\n');
}

function main() {
  const packagePath = join(PROJECT_ROOT, 'node_modules', 'tech-stack-icons', 'dist', 'index.js');

  if (!existsSync(packagePath)) {
    console.log('❌ tech-stack-icons not installed. Run: npm install tech-stack-icons@latest');
    process.exit(1);
  }

  const iconData = extractIconData(packagePath);
  const tsContent = generateTSModule(iconData);

  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const outputPath = join(OUTPUT_DIR, 'techIcons.ts');
  writeFileSync(outputPath, tsContent, 'utf-8');
  console.log(`✅ Generated: ${outputPath}`);
}

main();
